#!/usr/bin/env node
/* ==========================================================================
   build:knowledge — writes server/knowledge.json, what Moci's online brain
   (server/agent.mjs) knows about Adelia and the room.

   Why a generated file: the server is plain Node with zero dependencies and
   can't import TypeScript, while her facts live in src/content/*.ts and the
   room in src/stage/stations.ts. The same function the browser's offline
   brain uses (src/features/moci/knowledge.ts → knowledgeForServer()) is
   bundled here with esbuild (it ships with Vite) and its output saved as
   JSON, so both brains always answer from the same content.

   Run it whenever src/content/* or the stations change (the build does):
     npm run build:knowledge
   The JSON is committed too, so a server started without a build still has
   a recent copy. Deterministic: unchanged content → byte-identical file.
   ========================================================================== */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.resolve(root, process.env.KNOWLEDGE_OUT || 'server/knowledge.json');

/**
 * Bundle Moci's pure modules (knowledge, brain, evals) with esbuild and import the result.
 * Shared with scripts/eval-moci.mjs.
 */
export async function loadMoci() {
  let esbuild;
  try {
    esbuild = await import('esbuild');
  } catch {
    throw new Error('needs esbuild (installed with Vite). Run npm install.');
  }
  const dir = path.join(root, 'src/features/moci');
  const entry = [
    `export { knowledgeForServer, buildDocs, sources } from ${JSON.stringify(path.join(dir, 'knowledge.ts'))};`,
    `export { think, RECRUITER_QUESTIONS } from ${JSON.stringify(path.join(dir, 'brain.ts'))};`,
    `export { MOCI_CASES, describeAnswer } from ${JSON.stringify(path.join(dir, 'evals.ts'))};`,
  ].join('\n');
  const out = await esbuild.build({
    stdin: { contents: entry, resolveDir: dir, loader: 'ts', sourcefile: 'moci-node.ts' },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    target: 'node18',
    logLevel: 'silent',
    alias: { '@': path.join(root, 'src') },
    loader: { '.css': 'empty', '.svg': 'empty', '.png': 'empty', '.webp': 'empty', '.jpg': 'empty' },
  });
  return import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`);
}

async function main() {
  const moci = await loadMoci();
  const knowledge = moci.knowledgeForServer();
  const json = `${JSON.stringify({ about: 'Generated by scripts/build-knowledge.mjs from src/content and src/stage/stations.ts. Do not edit by hand.', ...knowledge }, null, 2)}\n`;
  let before = '';
  try {
    before = await fs.readFile(outFile, 'utf8');
  } catch {}
  if (before === json) {
    console.log(`build:knowledge: ${path.relative(root, outFile)} is up to date (${(json.length / 1024).toFixed(1)} KB)`);
    return;
  }
  await fs.writeFile(outFile, json);
  console.log(
    `build:knowledge: wrote ${path.relative(root, outFile)} (${(json.length / 1024).toFixed(1)} KB · ${knowledge.stations.length} stations · ${knowledge.works.length} case studies · ${knowledge.sources.length} sources)`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((e) => {
    console.error(`build:knowledge failed: ${e?.message || e}`);
    process.exit(1);
  });
}

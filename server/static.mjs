/* ==========================================================================
   Static file server for the Vite build (dist/).
   • Correct MIME types (incl. webp / avif / woff / woff2 / wasm / glb).
   • Brotli / gzip for compressible types (pre-compressed .br/.gz used when
     present, otherwise compressed once and cached in memory).
   • Hashed /assets/* files → immutable for a year; index.html → no-cache.
   • ETag / Last-Modified / 304, HEAD, single byte ranges.
   • SPA fallback: unknown extension-less GETs serve index.html.
   ========================================================================== */
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { compress, pickEncoding } from './util.mjs';

export const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.mp3': 'audio/mpeg',
  '.ogg': 'audio/ogg',
  '.wav': 'audio/wav',
  '.m4a': 'audio/mp4',
  '.mp4': 'video/mp4',
  '.webm': 'video/webm',
  '.wasm': 'application/wasm',
  '.glb': 'model/gltf-binary',
  '.gltf': 'model/gltf+json',
  '.hdr': 'application/octet-stream',
  '.ktx2': 'image/ktx2',
  '.pdf': 'application/pdf',
  '.csv': 'text/csv; charset=utf-8',
};

/** Friendly file names for files people save (the CV is generated by scripts/build-cv.mjs). */
const DISPOSITION = { '/cv.pdf': 'inline; filename="Adelia-Tiara-CV.pdf"' };

const COMPRESSIBLE = new Set(['.html', '.js', '.mjs', '.css', '.json', '.map', '.webmanifest', '.txt', '.xml', '.svg', '.ico', '.wasm', '.gltf', '.csv', '.ttf', '.otf']);
/** Vite's 8-char content-hash suffix, e.g. index-B3x_9aQf.js (must contain a digit/capital/_ so
 *  plain words like "-graphite.webp" from public/ are not mistaken for hashes). */
const HASHED = /-(?=[A-Za-z0-9_-]{0,7}[A-Z0-9_])[A-Za-z0-9_-]{8}\.[a-z0-9]+$/;

export function createStatic(root, log = console) {
  const rootAbs = path.resolve(root);
  const exists = fs.existsSync(path.join(rootAbs, 'index.html'));
  if (!exists) log.warn(`[static] ${rootAbs}/index.html not found — run "npm run build" first. The API still works.`);

  /** compressed bodies cached by path+mtime+enc (bounded by bytes) */
  const cache = new Map();
  let cacheBytes = 0;
  const CACHE_MAX = 64 * 1024 * 1024;

  function cachePut(k, buf) {
    if (buf.length > CACHE_MAX / 4) return;
    cache.set(k, buf);
    cacheBytes += buf.length;
    while (cacheBytes > CACHE_MAX && cache.size) {
      const [ok, ov] = cache.entries().next().value;
      cache.delete(ok);
      cacheBytes -= ov.length;
    }
  }

  function resolveSafe(urlPath) {
    let p;
    try {
      p = decodeURIComponent(urlPath);
    } catch {
      return null;
    }
    if (p.includes('\0')) return null;
    const abs = path.resolve(rootAbs, '.' + path.posix.normalize('/' + p));
    if (abs !== rootAbs && !abs.startsWith(rootAbs + path.sep)) return null;
    return abs;
  }

  async function statFile(abs) {
    try {
      const st = await fsp.stat(abs);
      if (st.isDirectory()) {
        const idx = path.join(abs, 'index.html');
        const st2 = await fsp.stat(idx).catch(() => null);
        return st2 && st2.isFile() ? { abs: idx, st: st2 } : null;
      }
      return st.isFile() ? { abs, st } : null;
    } catch {
      return null;
    }
  }

  function cacheControl(rel, ext) {
    if (ext === '.html') return 'no-cache';
    if (rel.startsWith('/assets/') && HASHED.test(rel)) return 'public, max-age=31536000, immutable';
    if (rel.startsWith('/assets/')) return 'public, max-age=86400, stale-while-revalidate=604800';
    return 'public, max-age=3600';
  }

  async function send(req, res, file, rel, setHeaders) {
    const { abs, st } = file;
    const ext = path.extname(abs).toLowerCase();
    const type = MIME[ext] || 'application/octet-stream';
    const etag = `W/"${st.size.toString(16)}-${Math.floor(st.mtimeMs).toString(16)}"`;
    setHeaders(res);
    res.setHeader('Content-Type', type);
    res.setHeader('Cache-Control', cacheControl(rel, ext));
    res.setHeader('ETag', etag);
    res.setHeader('Last-Modified', st.mtime.toUTCString());
    res.setHeader('Vary', 'Accept-Encoding');
    if (DISPOSITION[rel]) res.setHeader('Content-Disposition', DISPOSITION[rel]);

    const inm = req.headers['if-none-match'];
    if (inm && inm.split(',').some((t) => t.trim() === etag)) {
      res.statusCode = 304;
      res.end();
      return;
    }
    const ims = req.headers['if-modified-since'];
    if (!inm && ims && Math.floor(st.mtimeMs / 1000) <= Math.floor(Date.parse(ims) / 1000)) {
      res.statusCode = 304;
      res.end();
      return;
    }

    const enc = COMPRESSIBLE.has(ext) && st.size > 512 ? pickEncoding(req) : null;
    if (enc) {
      const key = `${abs}|${st.mtimeMs}|${enc}`;
      let body = cache.get(key);
      if (!body) {
        // prefer a pre-compressed sibling if the build produced one
        const pre = abs + (enc === 'br' ? '.br' : '.gz');
        const preSt = await fsp.stat(pre).catch(() => null);
        if (preSt && preSt.mtimeMs >= st.mtimeMs) body = await fsp.readFile(pre);
        else body = compress(await fsp.readFile(abs), enc, 'static');
        cachePut(key, body);
      }
      res.setHeader('Content-Encoding', enc);
      res.setHeader('Content-Length', body.length);
      res.statusCode = 200;
      res.end(req.method === 'HEAD' ? undefined : body);
      return;
    }

    res.setHeader('Accept-Ranges', 'bytes');
    const range = req.headers.range;
    if (range) {
      const m = /^bytes=(\d*)-(\d*)$/.exec(range.trim());
      if (m && (m[1] || m[2])) {
        let start = m[1] ? Number(m[1]) : Math.max(0, st.size - Number(m[2]));
        let end = m[1] && m[2] ? Math.min(Number(m[2]), st.size - 1) : st.size - 1;
        if (start <= end && start < st.size) {
          res.statusCode = 206;
          res.setHeader('Content-Range', `bytes ${start}-${end}/${st.size}`);
          res.setHeader('Content-Length', end - start + 1);
          if (req.method === 'HEAD') return void res.end();
          fs.createReadStream(abs, { start, end }).on('error', () => res.destroy()).pipe(res);
          return;
        }
        res.statusCode = 416;
        res.setHeader('Content-Range', `bytes */${st.size}`);
        return void res.end();
      }
    }
    res.statusCode = 200;
    res.setHeader('Content-Length', st.size);
    if (req.method === 'HEAD') return void res.end();
    fs.createReadStream(abs).on('error', () => res.destroy()).pipe(res);
  }

  /** @returns {Promise<boolean>} handled */
  return async function serveStatic(req, res, url, setHeaders) {
    if (req.method !== 'GET' && req.method !== 'HEAD') return false;
    const rel = url.pathname;
    const abs = resolveSafe(rel);
    if (abs) {
      const f = await statFile(abs);
      if (f) {
        await send(req, res, f, rel, setHeaders);
        return true;
      }
    }
    // Missing file with an extension (or under /assets) → real 404, never HTML-as-JS.
    if (rel.startsWith('/assets/') || /\.[a-z0-9]{1,8}$/i.test(rel)) return false;
    // SPA fallback
    const index = await statFile(path.join(rootAbs, 'index.html'));
    if (!index) {
      setHeaders(res);
      res.statusCode = 503;
      res.setHeader('Content-Type', 'text/html; charset=utf-8');
      res.setHeader('Cache-Control', 'no-store');
      res.end('<!doctype html><meta charset="utf-8"><title>Adelia\u2019s Room</title><p style="font:16px system-ui;padding:40px;color:#18263A;background:#F6F9FD">Adelia\u2019s Room is not built yet. Run <code>npm run build</code>, then restart the server.</p>');
      return true;
    }
    await send(req, res, index, '/index.html', setHeaders);
    return true;
  };
}
